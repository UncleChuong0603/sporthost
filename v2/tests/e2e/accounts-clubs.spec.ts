import { test, expect } from "@playwright/test";
const origin = process.env.SPORTHOST_E2E_ORIGIN || "http://127.0.0.1:3100";

test("host signs up, creates a real club, changes settings, and logs in again", async ({ page }, info) => {
  const email = `v2-browser-${info.project.name}-${Date.now()}@example.com`;
  await page.goto("/signup");
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Mật khẩu", { exact: true }).fill("browser-password-123");
  await page.getByRole("button", { name: "Tạo tài khoản", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await expect(page.getByRole("heading", { name: "Bắt đầu với câu lạc bộ đầu tiên" })).toBeVisible();
  await page.getByRole("link", { name: "Tạo câu lạc bộ", exact: true }).click();
  await page.getByLabel("Tên câu lạc bộ").fill("CLB cầu lông mới");
  await page.getByRole("combobox", { name: "Khu vực", exact: true }).fill("ho chi minh");
  await page.getByRole("option", { name: "Hồ Chí Minh", exact: true }).click();
  await page.getByLabel("Sức chứa mặc định").fill("15");
  await page.getByRole("button", { name: "Tạo câu lạc bộ", exact: true }).click();
  await expect(page.getByRole("heading", { name: "CLB cầu lông mới", exact: true })).toBeVisible();
  await page.getByLabel("Chính sách hủy").fill("Báo host trước buổi chơi.");
  await page.getByRole("button", { name: "Lưu cài đặt" }).click();
  await expect(page.getByRole("status")).toContainText("Đã lưu");
  await page.reload();
  await expect(page.getByRole("combobox", { name: "Khu vực", exact: true })).toHaveValue("Hồ Chí Minh");
  await expect(page.getByLabel("Chính sách hủy")).toHaveValue("Báo host trước buổi chơi.");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("link", { name: "Thành viên", exact: true }).last().click();
  await page.getByLabel("Họ tên", { exact: true }).fill("Người chơi mới");
  await page.getByLabel("Số điện thoại", { exact: true }).fill("+84 902 345 678");
  await page.getByRole("button", { name: "Thêm thành viên", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Đã thêm thành viên");
  await expect(page.getByRole("list").getByText("Người chơi mới", { exact: true })).toBeVisible();
  await expect(page.getByRole("list").locator("span").filter({ hasText: /^Chưa cập nhật$/ })).toBeVisible();
  await page.getByRole("link", { name: "Tài khoản", exact: true }).click();
  await expect(page.getByRole("button", { name: "Xác minh email", exact: true })).toBeDisabled();
  await page.getByLabel("Mật khẩu hiện tại", { exact: true }).fill("browser-password-123");
  await page.getByLabel("Mật khẩu mới", { exact: true }).fill("browser-password-changed-123");
  await page.getByLabel("Xác nhận mật khẩu mới", { exact: true }).fill("browser-password-changed-123");
  await page.getByRole("button", { name: "Lưu mật khẩu mới", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Đã đổi mật khẩu");
  await page.getByRole("button", { name: "Đăng xuất", exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Mật khẩu", { exact: true }).fill("wrong-password");
  await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
  await expect(page.getByText("Email hoặc mật khẩu không đúng.", { exact: true })).toBeVisible();
  await page.getByLabel("Mật khẩu", { exact: true }).fill("browser-password-changed-123");
  await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await expect(page.getByRole("heading", { name: "CLB cầu lông mới", exact: true })).toBeVisible();
});

test("legacy auth form POST preserves CSRF, cookie and 303 redirect", async ({ request, page }) => {
  await page.goto("/login");
  const csrf = await page.locator('input[name="csrf"]').inputValue();
  const response = await request.post("/signup", { form: { email: `v2-legacy-${Date.now()}@example.com`, password: "legacy-browser-password", csrf }, headers: { Origin: origin }, maxRedirects: 0 });
  expect(response.status(), (await response.text()).slice(0, 300)).toBe(303);
  expect(response.headers()["location"]).toBe(origin + "/dashboard");
  expect(response.headers()["set-cookie"]).toContain("HttpOnly");
  expect(response.headers()["set-cookie"]).toContain("SameSite=lax");
  const invalid = await request.post("/login", { form: { email: "fake@example.com", password: "password-123", csrf: "invalid" }, headers: { Origin: origin }, maxRedirects: 0 });
  expect(invalid.status()).toBe(403);
});
