import { test, expect } from "@playwright/test";

test("province dropdown supports searching, keyboard selection, dismissal and persistence", async ({ page }, info) => {
  await page.goto("/signup");
  await page.getByLabel("Email", { exact: true }).fill(`province-${info.project.name}-${Date.now()}@example.com`);
  await page.getByLabel("Mật khẩu", { exact: true }).fill("province-browser-password-123");
  await page.getByRole("button", { name: "Tạo tài khoản", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.goto("/clubs/new");
  await page.getByLabel("Tên câu lạc bộ").fill("CLB chọn khu vực");
  const region = page.getByRole("combobox", { name: "Khu vực", exact: true });
  await region.click();
  await expect(page.getByRole("listbox").getByRole("option")).toHaveCount(34);
  await expect(region).toHaveAttribute("aria-expanded", "true");
  await region.fill("xyz-no-province");
  await expect(page.getByText("Không tìm thấy tỉnh/thành phố", { exact: true })).toBeVisible();
  await region.press("Enter");
  await expect(page).toHaveURL(/\/clubs\/new$/);
  await page.getByRole("button", { name: "Xóa tìm kiếm", exact: true }).click();
  await expect(page.getByRole("listbox").getByRole("option")).toHaveCount(34);
  await region.fill("dak lak");
  await expect(page.getByRole("listbox").getByRole("option")).toHaveCount(1);
  await expect(page.getByRole("listbox").getByRole("option", { name: "Đắk Lắk", exact: true })).toBeVisible();
  await region.press("ArrowDown");
  await region.press("Enter");
  await expect(region).toHaveValue("Đắk Lắk");
  await expect(region).toHaveAttribute("aria-expanded", "false");
  await expect(page.locator('input[name="location"]')).toHaveValue("Đắk Lắk");
  await region.press("ArrowUp");
  await expect(page.getByRole("listbox").getByRole("option", { name: "Đắk Lắk", exact: true })).toHaveAttribute("aria-selected", "true");
  await region.fill("ha noi");
  await region.press("Escape");
  await expect(region).toHaveValue("Đắk Lắk");
  await region.click();
  await region.fill("ha noi");
  await page.getByRole("heading", { name: "Tạo câu lạc bộ", exact: true }).click();
  await expect(region).toHaveAttribute("aria-expanded", "false");
  await expect(region).toHaveValue("Đắk Lắk");
  await region.click();
  await region.fill("da nang");
  await page.getByRole("listbox").getByRole("option", { name: "Đà Nẵng", exact: true }).click();
  await region.press("ArrowDown");
  await region.press("Tab");
  await expect(region).toHaveAttribute("aria-expanded", "false");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Tạo câu lạc bộ", exact: true }).click();
  await expect(page.getByRole("heading", { name: "CLB chọn khu vực", exact: true })).toBeVisible();
  await page.reload();
  await expect(region).toHaveValue("Đà Nẵng");
});
