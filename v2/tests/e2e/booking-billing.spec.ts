import { test, expect } from "@playwright/test";
import { localNow } from "../../src/domain/session-policy";

test("group guest to attendance, exact sharing, receipt and close with debt", async ({ page, browser }, info) => {
  test.setTimeout(90000);
  await page.goto("/signup");
  await page.getByLabel("Email", { exact: true }).fill(`v2-full-${info.project.name}-${Date.now()}@example.com`);
  await page.getByLabel("Mật khẩu", { exact: true }).fill("browser-finance-password-123");
  await page.getByRole("button", { name: "Tạo tài khoản", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await page.goto("/clubs/new");
  await page.getByLabel("Tên câu lạc bộ").fill("CLB thử quy trình");
  await page.getByRole("button", { name: "Tạo câu lạc bộ", exact: true }).click();
  await expect(page.getByRole("heading", { name: "CLB thử quy trình", exact: true })).toBeVisible();
  await page.goto("/schedule/new");
  await page.getByLabel("Tên buổi chơi").fill("Chơi và chia phí");
  await page.getByLabel("Giờ bắt đầu").fill(localNow(new Date(Date.now() + 7 * 86400000)));
  await page.getByLabel("Sức chứa", { exact: true }).fill("3");
  await page.getByText("Lịch lặp, giới hạn và chính sách nâng cao", { exact: true }).click();
  await page.getByRole("combobox", { name: "Cách tính phí", exact: true }).selectOption("COST_SHARING");
  await page.getByRole("button", { name: "Tạo buổi chơi", exact: true }).click();
  await expect(page).toHaveURL(/\/games\/\d+$/);
  const gameUrl = page.url();
  const publicPath = await page.getByRole("link", { name: "Mở trang đăng ký công khai" }).getAttribute("href");
  const guestContext = await browser.newContext({ viewport: info.project.use.viewport });
  try {
    const guest = await guestContext.newPage(); await guest.goto(new URL(publicPath!, gameUrl).toString());
    await guest.getByLabel("Số điện thoại", { exact: true }).fill("0902345678");
    await guest.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await guest.getByLabel("Họ tên", { exact: true }).fill("Khách trả nhóm");
    await guest.getByText("Đăng ký hộ người đi cùng (tùy chọn)", { exact: true }).click();
    await guest.getByRole("button", { name: "Thêm người đi cùng", exact: true }).click();
    await guest.getByLabel("Tên người đi cùng 1", { exact: true }).fill("Bạn đi cùng");
    await guest.getByRole("button", { name: "Xác nhận gửi yêu cầu", exact: true }).click();
    await expect(guest.getByRole("status")).toContainText("Đã nhận đăng ký");
    await guest.getByRole("link", { name: "Xem đăng ký & thanh toán của tôi", exact: true }).click();
    await expect(guest.getByText("Chờ duyệt", { exact: true })).toBeVisible();
    await page.reload();
    await page.getByRole("button", { name: "Duyệt cả nhóm", exact: true }).click();
    await expect(page.getByText("2/3 chỗ", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Bắt đầu buổi chơi", exact: true }).click();
    const roster = page.getByRole("region", { name: "Danh sách người chơi" });
    await roster.getByRole("button", { name: "Có mặt", exact: true }).nth(0).click();
    await expect(roster.locator("p").filter({ hasText: /^Có mặt$/ })).toHaveCount(1);
    await roster.getByRole("button", { name: "Có mặt", exact: true }).nth(1).click();
    await page.getByRole("button", { name: "Kết thúc chơi", exact: true }).click();
    await page.getByRole("link", { name: "Thu chi và phát hành tiền cần đóng", exact: true }).click();
    await page.getByText("Thêm chi phí", { exact: true }).click();
    await page.getByLabel("Nội dung chi", { exact: true }).fill("Tiền sân");
    await page.getByLabel("Số tiền chi (đ)", { exact: true }).fill("100001");
    await page.getByRole("button", { name: "Lưu chi phí", exact: true }).click();
    await expect(page.getByText("50.001đ", { exact: true })).toBeVisible();
    await expect(page.getByText("50.000đ", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Phát hành tiền cần đóng", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Thu tiền và đối soát", exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await guest.reload();
    await expect(guest.getByRole("region", { name: "Thanh toán của bạn" }).getByText("100.001đ", { exact: true })).toHaveCount(2);
    await page.getByText("Ghi nhận tiền thực tế", { exact: true }).click();
    await page.getByLabel("Số tiền của Khách trả nhóm (đ)", { exact: true }).fill("60000");
    await page.getByRole("button", { name: "Lưu giao dịch", exact: true }).click();
    await expect(page.getByText("Đã thu một phần", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Chốt sổ", exact: true }).click();
    await expect(page.getByText(/Đã phát hành · phiên bản 1 · đã chốt sổ/)).toBeVisible();
    await guest.reload();
    await expect(guest.getByRole("region", { name: "Thanh toán của bạn" }).getByText("40.001đ", { exact: true })).toBeVisible();
    expect(await guest.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  } finally { await guestContext.close(); }
});
